`ifndef RADIX8_BOOTH_RECODER_SELECTOR_V
`define RADIX8_BOOTH_RECODER_SELECTOR_V

// -----------------------------------------------------------------------------
// 基-8 Booth 重编码与倍数选择器
//
// 本模块实现图 10.14 中一个基-8 Booth 预译码器。每次观察乘数的四元组
// {x_{i+2}, x_{i+1}, x_i, x_{i-1}}，产生一个属于 [-4, 4] 的 Booth 数字，
// 并选择 0、±a、±2a、±3a 或 ±4a。负倍数采用“按位取反 + extra_dot”的
// 进位保存表示：z_mult 只输出反码，extra_dot 在对应最低位补上二进制的 +1。
// 这样既避免了组合路径中的完整加法器，也能直接接入后级 CSA 阵列。
// -----------------------------------------------------------------------------
// ============================================================================
// 模块名称：radix8_booth_recoder_selector
// 对应教材：Behrooz Parhami《Computer Arithmetic》第 10.4 / 10.5 节
//           Figure 10.14 中的基-8 Booth 重编码与倍数选择组合逻辑模块
//
// ============================================================================
// 【子模块设计思路：我们是怎么设计基-8 Booth 编码与位宽防溢出机制的？】
//
// 1. 为什么输入乘数切片 x_quartet 是 4 位？
//    基-8（Radix-8，2^3 = 8）每次处理乘数的 3 个比特 {x_{i+2}, x_{i+1}, x_i}，加上低一位的重叠
//    扫描位 x_{i-1}，一共需要观察 4 个比特（即图 10.14 中顶部进入该模块前标注斜杠 4 的信号线）。
//    这 4 个比特构成的基-8 有符号数字权重公式为：
//        z = -4*x_{i+2} + 2*x_{i+1} + 1*x_i + 1*x_{i-1}，取值范围为对称的 [-4, +4]。
//
// 2. 为什么内部幅值统一对齐到 WIDTH+2 位，而最终输出 z_mult 要再扩 1 位到 WIDTH+3 位？
//    - 第一步（幅值对齐至 WIDTH+2 位）：
//      输入被乘数 a 是 WIDTH 位有符号补码，范围是 [-2^(WIDTH-1), +2^(WIDTH-1)-1]。
//      我们需要准备 {|1a|, |2a|, |3a|, |4a|} 四种幅值，其中最大的 4a 等于 a 左移 2 位 {a, 2'b00}，
//      占用了 WIDTH + 2 位。因此我们将 1a, 2a, 3a, 4a 全部通过有符号扩展对齐到 WIDTH + 2 位。
//    - 第二步（极值取反保护，再扩 1 位至 WIDTH+3 位）：
//      为什么要多扩这 1 位？考虑最极端的负数被乘数 a = -2^(WIDTH-1)，此时 4a = -2^(WIDTH+1)，
//      刚好达到 (WIDTH+2) 位补码的负数极限（最高位为 1，其余全 0）。
//      如果此时 Booth 编码恰好要求负倍数 -4a = -(-2^(WIDTH+1)) = +2^(WIDTH+1)，而 (WIDTH+2) 位
//      补码的最大正数只能表示到 +2^(WIDTH+1)-1，直接取反加 1 就会发生正溢出（符号位翻转成负数）！
//      因此，在执行按位取反之前，必须先将 WIDTH+2 位的 mux_mag 向上再复制 1 次符号位扩展到
//      WIDTH + 3 位，从而确保在任何极端正负数输入下都绝不会发生补码溢出！
//
// 3. 为什么不直接算出 -z*a 的完整补码，而是拆成反码 z_mult 和单比特 extra_dot？
//    在二补码中，求相反数等于“按位取反 + 1”。如果在子模块内部做“+1”，就需要放一个 (WIDTH+3) 位
//    的进位传播加法器，这会严重拖慢延迟！因此我们只用一层异或门/反相器输出按位取反后的 z_mult，
//    而把负号标志 neg 作为 extra_dot 单独引出，交给后级 CSA / 6-bit 加法器的天然空槽去顺便完成“+1”！
// ============================================================================
module radix8_booth_recoder_selector #(
    parameter WIDTH = 36  // 被乘数 a 的位宽 k
)(
    input  wire [WIDTH-1:0]   a,          // k 位有符号补码被乘数 (1a)
    input  wire [WIDTH+1:0]   a_3,        // (k+2) 位由顶层预计算好的有符号补码 3a
    input  wire [3:0]         x_quartet,  // 4 位重叠扫描乘数窗口 {x_{i+2}, x_{i+1}, x_i, x_{i-1}}
    output wire [WIDTH+2:0]   z_mult,     // (k+3) 位补码倍数的反码（负倍数时）或原码（非负倍数时）输出
    output wire               extra_dot   // 1 位额外点输出（当为负倍数时等于 1，用于后级完成取反加一的 +1 补偿）
);
    // ========================================================================
    // 一、 内部信号集中声明区
    // ========================================================================

    // 内部信号
    // 所有中间信号集中声明在此处，确保综合器在组合逻辑分析时能够看到
    // 完整的位宽。WIDTH+2 位用于表示 1a、2a、3a、4a 的统一内部格式，
    // 再向上扩展一位后得到 WIDTH+3 位输出，保留极值运算的符号位。
    wire [WIDTH+1:0] wire_1a;       // 符号扩展至 k+2 位的有符号 1a
    wire [WIDTH+1:0] wire_2a;       // 符号扩展并左移 1 位至 k+2 位的有符号 2a
    wire [WIDTH+1:0] wire_3a;       // 直接接收顶层传入的 k+2 位有符号 3a
    wire [WIDTH+1:0] wire_4a;       // 左移 2 位至 k+2 位的有符号 4a
    reg  [WIDTH+1:0] mux_mag;       // 5 选 1 MUX 选出的 k+2 位倍数幅值 (0, 1a, 2a, 3a, 4a)
    wire             neg;           // 负倍数标志（1 代表 z < 0，需按位取反并加 1）
    wire [WIDTH+2:0] mux_mag_ext;   // 将 mux_mag 向上再做 1 位符号扩展至 k+3 位，防止 -4a 取反溢出

    // ========================================================================
    // 二、 基础倍数对齐（统一对齐至 WIDTH+2 位有符号补码）
    // 有符号倍数预计算与符号扩展
    //
    // 1a 直接复制 a 的符号位两次；2a 通过拼接一个符号位和一个低位零
    // 实现算术左移一位；3a 已由顶层加法器预先算好；4a 通过左移两位形成。
    // 这里的拼接是显式的，避免 Verilog 无符号表达式在位宽扩展时丢失符号。
    // ========================================================================
    
    assign wire_1a = {{2{a[WIDTH-1]}}, a};      // 1a：高位复制 2 次符号位 a[WIDTH-1]
    assign wire_2a = {a[WIDTH-1], a, 1'b0};     // 2a：高位复制 1 次符号位，低位补 1 个 0（算术左移 1 位）
    assign wire_3a = a_3;                       // 3a：已在顶层 PRE_CALC 状态算出 k+2 位有符号 3a
    assign wire_4a = {a, 2'b00};                // 4a：低位补 2 个 0（算术左移 2 位，原符号位自然推至第 WIDTH+1 位）

    // ========================================================================
    // 基-8 Booth 编码表
    //
    // 基-8 重编码的数值为
    //     z = -4*x_{i+2} + 2*x_{i+1} + x_i + x_{i-1}，其中 z 属于 [-4,+4]。
    // 【真值表规律】：正负对称的码字（即按位取反的码字，如 0001(+1) 与 1110(-1)）共享相同的幅值 mux_mag，
    // 仅靠下方的 neg 信号区分正负号，从而将 9 种可能结果 (-4 ~ +4) 简化为 5 选 1 多路选择器：
    // 对称码字共享同一个幅值：
    //   0000/1111 -> 0；
    //   0001/0010/1101/1110 -> |1a|；
    //   0011/0100/1011/1100 -> |2a|；
    //   0101/0110/1001/1010 -> |3a|；
    //   0111/1000 -> |4a|。
    // mux_mag 只选择幅值的位模式，正负号稍后由 neg 统一处理。这种拆分允许同一组倍数生成硬件同时服务正倍数和负倍数，减少 MUX 规模。
    // ========================================================================
    always @(*) begin
        case (x_quartet)
            4'b0000,
            4'b1111: mux_mag = {(WIDTH+2){1'b0}};

            4'b0001,
            4'b0010,
            4'b1101,
            4'b1110: mux_mag = wire_1a;

            4'b0011,
            4'b0100,
            4'b1011,
            4'b1100: mux_mag = wire_2a;

            4'b0101,
            4'b0110,
            4'b1001,
            4'b1010: mux_mag = wire_3a;

            4'b0111,
            4'b1000: mux_mag = wire_4a;

            default: mux_mag = {(WIDTH+2){1'b0}};
        endcase
    end

    // 最高位为 1 的码字表示负倍数；1111 是“负零”编码，必须排除，
    // 否则会错误地产生全一反码并额外加一。其余码字的负号由最高位
    // x_{i+2} 直接给出，因此该逻辑等价于 Booth 表的符号判定。
    assign neg = x_quartet[3] & (x_quartet != 4'b1111);

    // ========================================================================
    // 四、 符号判定与选择性按位取反（防“-0”陷阱与极值防溢出扩展）
    // ========================================================================
    // 【为什么要加 (x_quartet != 4'b1111)？】
    // 当 x_quartet 为 1000~1110 时，数学权重 z 为 -4 ~ -1（均为负数，最高位 x_quartet[3] == 1）；
    // 但当 x_quartet == 4'b1111 时，z = -4 + 2 + 1 + 1 = 0！如果只看最高位 x_quartet[3] == 1，
    // 就会把 4'b1111 误判为“负零（-0）”。虽然全 0 取反变成全 1 后加上 extra_dot=1 在无限位宽下会归零，
    // 但在有限位宽的 CSA 中会产生不必要的高位进位干扰！因此必须显式排除 4'b1111，确保 0 倍数时 neg = 0。


    // 选择性求补与极值保护
    // mux_mag 先复制其最高符号位扩展到 k+3 位，再在负倍数时逐位取反。
    // 多出的这一位是必要的：当 a = -2^(k-1) 时，4a = -2^(k+1)，其
    // 反码形式必须在 k+3 位容纳最高符号位，才能让后级 extra_dot 加一后
    // 保持正确的补码数学权重。extra_dot 与 z_mult 的最低位权重相同，
    // 由后级 CSA 将它放入对应的空槽中完成 +1。

    // 向上符号扩展 1 位至 WIDTH+3 位后，根据 neg 执行选择性按位取反，并将 neg 作为 extra_dot 输出
    assign mux_mag_ext = {{1{mux_mag[WIDTH+1]}}, mux_mag};
    assign z_mult      = neg ? ~mux_mag_ext : mux_mag_ext;
    assign extra_dot   = neg;

endmodule

`endif
